function get(id) {
  return FLOWS.find((f) => f.id === id) || null;
}

// 给网页用的精简描述（不含提示词）
function publicList() {
  return FLOWS.map((f) => ({
    id: f.id,
    icon: f.icon,
    name: f.name,
    desc: f.desc,
    placeholder: f.placeholder,
    requireText: !!f.requireText,
    next: f.next || null,
    steps: f.steps.map((s) => ({ label: s.label, who: s.who, ask: !!s.ask })),
  }));
}

module.exports = { FLOWS, get, publicList };
